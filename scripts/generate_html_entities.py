#!/usr/bin/env python3
"""Generate src/vxml/internal/html_entities.gleam from glentities' decoder.

Usage (from the vxml directory, after `gleam deps download`):

    python3 scripts/generate_html_entities.py \
        build/packages/glentities/src/glentities/decoder.gleam \
        > src/vxml/internal/html_entities.gleam

glentities' `decode_named` is one `case` with ~2,100 string branches. Gleam
compiles it to a single JavaScript `if / else if` chain, which browsers fail
to parse ("Maximum call stack size exceeded"), so any page importing it
breaks. The generated module dispatches on the first letter first, keeping
every chain under ~170 branches.
"""

import re
import sys
from collections import OrderedDict

ENTRY = re.compile(r'^    "([A-Za-z0-9]+)" -> ("(?:[^"\\]|\\.)*")$')


def group_function(first: str) -> str:
    """Gleam function names are lowercase, so encode the letter's case."""
    case = "upper" if first.isupper() else "lower"
    return f"named_{case}_{first.lower()}"


def main(path: str) -> None:
    groups: "OrderedDict[str, list[tuple[str, str]]]" = OrderedDict()
    with open(path, encoding="utf-8") as source:
        in_decode_named = False
        for line in source:
            line = line.rstrip("\n")
            if line.startswith("pub fn decode_named("):
                in_decode_named = True
                continue
            if not in_decode_named:
                continue
            match = ENTRY.match(line)
            if match:
                name, literal = match.groups()
                groups.setdefault(name[0], []).append((name[1:], literal))
    if not groups:
        sys.exit(f"no named entities found in {path}")

    out = sys.stdout
    out.write(
        "//// HTML character-reference decoding, with the same results as\n"
        "//// `glentities/decoder` 6.2.2.\n"
        "////\n"
        "//// GENERATED by scripts/generate_html_entities.py from glentities'\n"
        "//// decoder (MIT licence, (c) 2023 Mikko Ahlroth). Do not edit.\n"
        "////\n"
        "//// The named-entity table dispatches on the first letter so that no\n"
        "//// compiled JavaScript `if / else if` chain is long enough to overflow a\n"
        "//// browser's parser, which glentities' single `case` does.\n"
        "\n"
        "import gleam/int\n"
        "import gleam/string\n"
        "\n"
        "/// Decodes a hexadecimal reference body (without `&#x` and `;`). Returns\n"
        "/// the input unchanged if it is not a valid code point.\n"
        "pub fn decode_hex(entity: String) -> String {\n"
        "  case int.base_parse(entity, 16) {\n"
        "    Ok(codepoint) -> from_codepoint(codepoint, entity)\n"
        "    Error(_) -> entity\n"
        "  }\n"
        "}\n"
        "\n"
        "/// Decodes a decimal reference body (without `&#` and `;`). Returns the\n"
        "/// input unchanged if it is not a valid code point.\n"
        "pub fn decode_dec(entity: String) -> String {\n"
        "  case int.parse(entity) {\n"
        "    Ok(codepoint) -> from_codepoint(codepoint, entity)\n"
        "    Error(_) -> entity\n"
        "  }\n"
        "}\n"
        "\n"
        "fn from_codepoint(codepoint: Int, entity: String) -> String {\n"
        "  case string.utf_codepoint(codepoint) {\n"
        "    Ok(utf_codepoint) -> string.from_utf_codepoints([utf_codepoint])\n"
        "    Error(_) -> entity\n"
        "  }\n"
        "}\n"
        "\n"
        "/// Decodes a named reference body (without `&` and `;`). Returns\n"
        "/// `\"&\" <> entity <> \";\"` if it is not a known entity name.\n"
        "pub fn decode_named(entity: String) -> String {\n"
        "  let found = case entity {\n"
    )
    for first in groups:
        out.write(f'    "{first}" <> rest -> {group_function(first)}(rest)\n')
    out.write(
        '    _ -> Error(Nil)\n'
        "  }\n"
        "  case found {\n"
        "    Ok(decoded) -> decoded\n"
        '    Error(Nil) -> "&" <> entity <> ";"\n'
        "  }\n"
        "}\n"
    )
    for first, entries in groups.items():
        out.write(
            f"\nfn {group_function(first)}(rest: String) -> Result(String, Nil) {{\n"
        )
        out.write("  case rest {\n")
        for suffix, literal in entries:
            out.write(f'    "{suffix}" -> Ok({literal})\n')
        out.write("    _ -> Error(Nil)\n  }\n}\n")


if __name__ == "__main__":
    if len(sys.argv) != 2:
        sys.exit(__doc__)
    main(sys.argv[1])
