#!/usr/bin/env python3
"""Generate src/vxml/internal/html_entities.gleam from glentities' decoder and
named encoder.

Usage (from the vxml directory, after `gleam deps download`):

    python3 scripts/generate_html_entities.py \
        build/packages/glentities/src/glentities/decoder.gleam \
        build/packages/glentities/src/glentities/named_encoder.gleam \
        > src/vxml/internal/html_entities.gleam

glentities' `decode_named` is one `case` with ~2,100 string branches, and its
named encoder one with ~1,500. Gleam compiles each to a single JavaScript
`if / else if` chain, which browsers fail to parse ("Maximum call stack size
exceeded") and Bun's bundler crashes on. The generated module dispatches on
the first letter (decoding) or the first code point's 64-code-point block
(encoding) first, keeping every chain under ~170 branches.
"""

import re
import sys
from collections import OrderedDict

ENTRY = re.compile(r'^    "([A-Za-z0-9]+)" -> ("(?:[^"\\]|\\.)*")$')
ENCODE_ENTRY = re.compile(
    r'^    ("(?:[^"\\]|\\.)*") <> rest -> do_encode\(rest, append\(acc, ("&[A-Za-z0-9]+;")\)\)$'
)
ESCAPE = re.compile(r'\\(u\{[0-9A-Fa-f]+\}|.)')
ESCAPES = {"n": "\n", "t": "\t", "r": "\r", "f": "\f", '"': '"', "\\": "\\"}


def group_function(first: str) -> str:
    """Gleam function names are lowercase, so encode the letter's case."""
    case = "upper" if first.isupper() else "lower"
    return f"named_{case}_{first.lower()}"


def gleam_string_value(literal: str) -> str:
    def unescape(match: "re.Match[str]") -> str:
        escape = match.group(1)
        if escape.startswith("u{"):
            return chr(int(escape[2:-1], 16))
        return ESCAPES[escape]

    return ESCAPE.sub(unescape, literal[1:-1])


def encode_blocks(path: str) -> "OrderedDict[int, list[tuple[str, str]]]":
    """Entries keep glentities' order within a block. Entries in different
    blocks start with different code points, so they never compete."""
    blocks: "OrderedDict[int, list[tuple[str, str]]]" = OrderedDict()
    with open(path, encoding="utf-8") as source:
        for line in source:
            match = ENCODE_ENTRY.match(line.rstrip("\n"))
            if match:
                literal, entity = match.groups()
                block = ord(gleam_string_value(literal)[0]) // 64
                blocks.setdefault(block, []).append((literal, entity))
    if not blocks:
        sys.exit(f"no named entities found in {path}")
    return OrderedDict(sorted(blocks.items()))


def main(path: str, encoder_path: str) -> None:
    blocks = encode_blocks(encoder_path)
    groups: "OrderedDict[str, list[tuple[str, str]]]" = OrderedDict()
    with open(path, encoding="utf-8") as source:
        in_decode_named = False
        for line in source:
            line = line.rstrip("\n")
            if line.startswith("pub fn decode_named("):
                in_decode_named = True
                continue
            if not in_decode_named:
                continue
            match = ENTRY.match(line)
            if match:
                name, literal = match.groups()
                groups.setdefault(name[0], []).append((name[1:], literal))
    if not groups:
        sys.exit(f"no named entities found in {path}")

    out = sys.stdout
    out.write(
        "//// HTML character-reference decoding and named-entity encoding, with the\n"
        "//// same results as `glentities/decoder` and `glentities/named_encoder`\n"
        "//// 6.2.2.\n"
        "////\n"
        "//// GENERATED by scripts/generate_html_entities.py from glentities'\n"
        "//// decoder and named encoder (MIT licence, (c) 2023 Mikko Ahlroth).\n"
        "//// Do not edit.\n"
        "////\n"
        "//// The tables dispatch on the first letter (decoding) or the first code\n"
        "//// point's 64-code-point block (encoding) so that no compiled JavaScript\n"
        "//// `if / else if` chain is long enough to overflow a browser's parser or\n"
        "//// Bun's bundler, which glentities' single `case`s do.\n"
        "\n"
        "import gleam/int\n"
        "import gleam/string\n"
        "\n"
        "/// Decodes a hexadecimal reference body (without `&#x` and `;`). Returns\n"
        "/// the input unchanged if it is not a valid code point.\n"
        "pub fn decode_hex(entity: String) -> String {\n"
        "  case int.base_parse(entity, 16) {\n"
        "    Ok(codepoint) -> from_codepoint(codepoint, entity)\n"
        "    Error(_) -> entity\n"
        "  }\n"
        "}\n"
        "\n"
        "/// Decodes a decimal reference body (without `&#` and `;`). Returns the\n"
        "/// input unchanged if it is not a valid code point.\n"
        "pub fn decode_dec(entity: String) -> String {\n"
        "  case int.parse(entity) {\n"
        "    Ok(codepoint) -> from_codepoint(codepoint, entity)\n"
        "    Error(_) -> entity\n"
        "  }\n"
        "}\n"
        "\n"
        "fn from_codepoint(codepoint: Int, entity: String) -> String {\n"
        "  case string.utf_codepoint(codepoint) {\n"
        "    Ok(utf_codepoint) -> string.from_utf_codepoints([utf_codepoint])\n"
        "    Error(_) -> entity\n"
        "  }\n"
        "}\n"
        "\n"
        "/// Decodes a named reference body (without `&` and `;`). Returns\n"
        "/// `\"&\" <> entity <> \";\"` if it is not a known entity name.\n"
        "pub fn decode_named(entity: String) -> String {\n"
        "  let found = case entity {\n"
    )
    for first in groups:
        out.write(f'    "{first}" <> rest -> {group_function(first)}(rest)\n')
    out.write(
        '    _ -> Error(Nil)\n'
        "  }\n"
        "  case found {\n"
        "    Ok(decoded) -> decoded\n"
        '    Error(Nil) -> "&" <> entity <> ";"\n'
        "  }\n"
        "}\n"
    )
    for first, entries in groups.items():
        out.write(
            f"\nfn {group_function(first)}(rest: String) -> Result(String, Nil) {{\n"
        )
        out.write("  case rest {\n")
        for suffix, literal in entries:
            out.write(f'    "{suffix}" -> Ok({literal})\n')
        out.write("    _ -> Error(Nil)\n  }\n}\n")

    out.write(
        "\n"
        "/// Encodes, after NFC normalisation, every character that has a named\n"
        "/// HTML entity, except newline and tab. Other characters are unchanged.\n"
        "pub fn encode_named(text: String) -> String {\n"
        '  encode_named_loop(normalise(text), "")\n'
        "}\n"
        "\n"
        "fn encode_named_loop(text: String, encoded: String) -> String {\n"
        "  case string.pop_grapheme(text) {\n"
        "    Error(Nil) -> encoded\n"
        "    Ok(#(grapheme, after_grapheme)) -> {\n"
        "      let found = case string.to_utf_codepoints(grapheme) {\n"
        "        [first, ..] ->\n"
        "          encode_block(string.utf_codepoint_to_int(first) / 64, text)\n"
        "        [] -> Error(Nil)\n"
        "      }\n"
        "      case found {\n"
        "        Ok(#(entity, rest)) -> encode_named_loop(rest, encoded <> entity)\n"
        "        Error(Nil) -> encode_named_loop(after_grapheme, encoded <> grapheme)\n"
        "      }\n"
        "    }\n"
        "  }\n"
        "}\n"
        "\n"
        '@external(erlang, "unicode", "characters_to_nfc_binary")\n'
        '@external(javascript, "./html_entities_ffi.mjs", "normalise")\n'
        "fn normalise(text: String) -> String\n"
        "\n"
        "fn encode_block(block: Int, text: String) -> Result(#(String, String), Nil) {\n"
        "  case block {\n"
    )
    for block in blocks:
        out.write(f"    {block} -> encode_block_{block}(text)\n")
    out.write("    _ -> Error(Nil)\n  }\n}\n")
    for block, entries in blocks.items():
        out.write(
            f"\nfn encode_block_{block}(text: String) -> Result(#(String, String), Nil) {{\n"
        )
        out.write("  case text {\n")
        for literal, entity in entries:
            out.write(f"    {literal} <> rest -> Ok(#({entity}, rest))\n")
        out.write("    _ -> Error(Nil)\n  }\n}\n")


if __name__ == "__main__":
    if len(sys.argv) != 3:
        sys.exit(__doc__)
    main(sys.argv[1], sys.argv[2])
